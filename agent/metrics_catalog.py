"""Atlas process-measurement catalog for per-node metric graphs.

Pure data and request planning only (no I/O, no plotting), so the collector skill and the
report stage share one definition.

* ``DEFAULT_GRAPH_CONFIG`` mirrors the ``cluster.per_node.graph`` template used by slowInvest:
  ``group_of_metrics`` defines every available group, ``metrics`` selects the groups graphed.
* ``ATLAS_PROCESS_MEASUREMENTS`` is the documented value list of the ``m`` query parameter of
  ``GET /groups/{groupId}/processes/{processId}/measurements`` (Atlas Admin API v2).
  Atlas rejects the whole request when any ``m`` value is invalid, so only listed names are
  requested; each request carries at most ``MAX_M_PER_REQUEST`` values.
* Template names absent from the documented list are either mapped by ``MEASUREMENT_ALIASES``
  to their documented equivalent, or kept for plotting only (they can still appear in a
  supplied/bucket ``metrics.json``) and reported as not requestable.
"""
