def graph_config(config: dict | None = None) -> dict:
    """Return the effective ``{group_of_metrics, metrics}`` graph configuration.

    ``metrics_graph_config`` may override either key (same shape as the slowInvest template);
    ``metrics_graph_groups`` may override only the selected group list.
    """
    config = config or {}
    override = config.get("metrics_graph_config") or {}
    groups = dict(DEFAULT_GRAPH_CONFIG["group_of_metrics"])
    groups.update(override.get("group_of_metrics") or {})
    selected = config.get("metrics_graph_groups") or override.get("metrics") or DEFAULT_GRAPH_CONFIG["metrics"]
    return {"group_of_metrics": groups, "metrics": [g for g in selected if g in groups]}


def selected_groups(config: dict | None = None) -> list[tuple[str, list[str]]]:
    """Ordered ``(group, template metric names)`` for the selected groups."""
    cfg = graph_config(config)
    return [(name, list(cfg["group_of_metrics"][name].get("list_of_metrics", [])))
            for name in cfg["metrics"]]


def api_name(name: str) -> str:
    return MEASUREMENT_ALIASES.get(name, name)


def plan_measurement_requests(config: dict | None = None) -> dict:
    """Plan the ``m`` values needed for the selected groups.

    Returns ``{"batches": [[m, ...], ...], "requested": [...], "unsupported": [...],
    "aliases": {template: api}}``; every batch has at most ``MAX_M_PER_REQUEST`` names.
    """
    requested, unsupported, aliases = [], [], {}
    for _group, names in selected_groups(config):
        for name in names:
            target = api_name(name)
            if target != name:
                aliases[name] = target
            if target not in ATLAS_PROCESS_MEASUREMENTS:
                if name not in unsupported:
                    unsupported.append(name)
            elif target not in requested:
                requested.append(target)
    batches = [requested[i:i + MAX_M_PER_REQUEST] for i in range(0, len(requested), MAX_M_PER_REQUEST)]
    return {"batches": batches, "requested": requested, "unsupported": unsupported, "aliases": aliases}
